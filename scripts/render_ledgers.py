#!/usr/bin/env python3
"""Render reviewable ledgers from the canonical research database (stdlib only)."""
import argparse
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / 'research/RESEARCH_DATABASE.json'
TABLES = {
 'claims': ('01_source_lock/CLAIM_REGISTRY.csv', 'claim_registry'),
 'objects': ('02_eta_reconstruction/OBJECT_DICTIONARY.csv', 'object_dictionary'),
 'maps': ('02_eta_reconstruction/MAP_DICTIONARY.csv', 'map_dictionary'),
 'steps': ('02_eta_reconstruction/ETA_ALGORITHM.csv', 'eta_algorithm'),
 'choices': ('03_admissibility_orbit/CHOICE_REGISTRY.csv', 'choice_registry'),
 'indeterminacies': ('03_admissibility_orbit/INDETERMINACY_LEDGER.csv', 'indeterminacy_ledger'),
 'orbits': ('03_admissibility_orbit/ORBIT_LEDGER.csv', 'orbit_ledger'),
 'invariants': ('03_admissibility_orbit/INVARIANT_CANDIDATES.csv', 'invariant_candidates'),
 'questions': ('02_eta_reconstruction/OPEN_INTERPRETATION_QUESTIONS.csv', 'open_questions'),
}
EVIDENCE = ['SOURCE FACT','SOURCE CLAIM','RECONSTRUCTION','INFERENCE','OPEN QUESTION']
CLAIM_STATUS = ['VERIFIED_PRIMARY','VERIFIED_SECONDARY','SOURCE_CLAIM_ONLY','RECONSTRUCTION','HYPOTHESIS','UNRESOLVED','CONTRADICTED']
INVARIANT_STATUS = ['PROVEN INVARIANT','PLAUSIBLE','DISPROVEN','UNKNOWN']


def schema_for(key, rows):
    props = {name: {'type':'string'} for name in rows[0]}
    props['evidence_type']['enum'] = EVIDENCE
    if key == 'claims': props['status']['enum'] = CLAIM_STATUS
    if key == 'invariants': props['status']['enum'] = INVARIANT_STATUS
    return {'$schema':'https://json-schema.org/draft/2020-12/schema',
            'title':TABLES[key][1], 'type':'array', 'minItems':1,
            'items':{'type':'object','required':list(props),
                     'additionalProperties':False,'properties':props}}


def row_markdown(row, heading_field):
    lines = [f"## {row[heading_field]}\n"]
    for name,value in row.items():
        if name != heading_field:
            lines.append(f"- **{name.replace('_',' ')}:** {value or 'NONE LISTED'}")
    return '\n'.join(lines)+'\n'


def render(db):
    out = {}
    for key,(path,schema_name) in TABLES.items():
        rows = db[key]
        stream = io.StringIO(newline='')
        writer = csv.DictWriter(stream,fieldnames=list(rows[0]),lineterminator='\n')
        writer.writeheader(); writer.writerows(rows)
        out['research/'+path] = stream.getvalue()
        out['schemas/'+schema_name+'.schema.json'] = json.dumps(schema_for(key,rows),indent=2)+'\n'
    algorithm = """# η algorithm — nine source steps

Generated by `python3 scripts/render_ledgers.py` from `research/RESEARCH_DATABASE.json`.

**SOURCE FACT [C001, C003]:** LANA §9.1(a)–(i), PDF pp.44–45, explicitly numbers nine steps. Its §6.2 is a different, earlier presentation. The numbering here follows §9.1. Source descriptions are not certificates that each compressed construction has been fully reconstructed.

**RECONSTRUCTION [R_S03–R_S09]:** Keep the following typed chain distinct:

`M_infty —κ→ ∞H¹(Π,Λ) —rigidity→ ∞H¹(Π,ℓΔᶜ) —restriction→ ∏∞H¹(D_t,ℓΔᶜ) ←φ— ∏Obar_t^▷`.

The asserted factorization supplies a separate arrow from `M_infty` to the local monoids. Step 7 then uses their chosen field embedding and the inverse of the unit-quotient logarithm. This is not a direct logarithm of a nonunit. A construction edge in the dictionaries is explicitly marked `CONSTRUCTION`; it is not asserted to be a function on elements.

**OPEN QUESTION [R_U03, R_U05]:** Step 3 prints ordinary H¹, while Figure 6 and subsequent steps use ∞H¹. Step 6 prints barred local monoids and Step 7 unbarred ones. We preserve these differences pending domain/restriction reconciliation. Page renders are saved in `evidence/`.

**OPEN QUESTION [R_U04, R_U05, R_U08]:** Steps 6–9 are HIGH-PRIORITY COMPATIBILITY STEPS. Their required synchronization, compact structures and vertical comparison have not been expanded into a complete admissibility predicate.

"""
    algorithm += '\n'.join(row_markdown(r,'step_id') for r in db['steps'])
    out['research/02_eta_reconstruction/ETA_ALGORITHM.md'] = algorithm
    inv = """# Candidate invariants and exact scope

Generated from the research database. **RECONSTRUCTION:** “PROVEN INVARIANT” below means a preservation statement or normalization law at the explicitly stated source scope. It does not certify a constant on the full, unresolved η family. Some entries are laws rather than numerical invariants. No entry is certified as a full-orbit separating invariant [C018; R_U08].

The strongest extracted normalization constraint is J08 together with J09: the fixed prime-multiplication law and prescribed packet/permutation averaging. J06 records the potentially relevant synchronized first-power datum. Which of these survives every admissible η transformation is UNKNOWN. No obstruction search was performed.

"""
    out['research/03_admissibility_orbit/INVARIANT_CANDIDATES.md'] = inv+'\n'.join(row_markdown(r,'invariant_id') for r in db['invariants'])
    questions = """# Open interpretation questions

Generated from the research database. These are boundaries of this audit, not assertions that the sources have no answers. Resolving a question requires the specified source structures and a recorded claim update; a toy model or arbitrary scalar identification does not resolve it.

"""
    out['research/02_eta_reconstruction/OPEN_INTERPRETATION_QUESTIONS.md'] = questions+'\n'.join(row_markdown(r,'question_id') for r in db['questions'])
    return out


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    generated=render(json.loads(DB_PATH.read_text()))
    stale=[]
    for path,content in generated.items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_text()!=content: stale.append(path)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_text(content)
    if stale: raise SystemExit('STALE: '+', '.join(stale))
    print(('Checked' if args.check else 'Generated')+f' {len(generated)} ledger/schema views')

if __name__=='__main__':main()
